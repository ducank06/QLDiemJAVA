    private void btnloginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnloginActionPerformed
        // TODO add your handling code here:
        String username = txtusername.getText().trim();
        String password = new String(txtpassword.getPassword());
        
        if (username.trim().isEmpty() || password.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ tài khoản và mật khẩu!", "Cảnh báo", JOptionPane.WARNING_MESSAGE);
        return;
        }
        String sql = "SELECT vai_tro, ma_gv FROM tai_khoan "
                + "WHERE ten_dn = ? AND mat_khau = SHA2(?, 256) AND kich_hoat = 1";
        try (Connection conn = KNCSDL.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, username);
            ps.setString(2, password);
            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    MainMenu.vaiTro = rs.getString("vai_tro");
                    MainMenu.maGV = rs.getString("ma_gv");
                    MainMenu.tenDangNhap = username;
                    new MainMenu().setVisible(true);
                    dispose();
                } else {
                    JOptionPane.showMessageDialog(this, "Tài khoản hoặc mật khẩu không đúng, hoặc tài khoản đã bị khóa.", "Đăng nhập thất bại", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (IllegalStateException | SQLException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Lỗi kết nối", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Không thể đăng nhập: " + e.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnloginActionPerformed

