    private void SqlSV(String sql,boolean update){
        try{
            String id=required(txtMaSV,"Mã sinh viên"),name=required(txtHoten,"Họ tên"),date=txtNgaysinh.getText().trim();
            String gender = btnNu.isSelected() ? "NU" : "NAM";
            String phone = txtsdt.getText().trim();
            String email = txtemail.getText().trim();
            String address = txtdiachi.getText().trim();
            String clazz = required(txtlop, "Mã lớp");
            String state=String.valueOf(jComboBox2.getSelectedItem());
            state=state.equals("Bảo lưu")?"BAO_LUU":state.equals("Tốt Nghiệp")?"TOT_NGHIEP":"DANG_HOC";
            
            if(!email.isEmpty()&&!email.matches("^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$"))
                throw new IllegalArgumentException("Email không đúng định dạng.");
            
            if(!phone.isEmpty()&&!phone.matches("[0-9]{9,15}"))
                throw new IllegalArgumentException("Số điện thoại cần từ 9 đến 15 chữ số.");
            
            Date dob=date.isEmpty()?null:Date.valueOf(date);
            try(Connection c=KNCSDL.getConnection();
                    PreparedStatement p=c.prepareStatement(sql)){
                if(update){p.setString(1,name);
                p.setDate(2, dob);
                p.setString(3,gender);
                p.setString(4,email);
                p.setString(5,phone);
                p.setString(6,address);
                p.setString(7,clazz);
                p.setString(8,state);p.setString(9,id);}
                else{p.setString(1,id);p.setString(2,name);p.setDate(3,dob);p.setString(4,gender);
                p.setString(5,email);p.setString(6,phone);p.setString(7,address);
                p.setString(8,clazz);p.setString(9,state);}
                p.executeUpdate();
            }loadSV();
            clearSV();
        }catch(Exception e){showError(e);}
    }
    private void XoaSV(){
        int row=tblSinhVien.getSelectedRow();
        String id=row<0?txtMaSV.getText().trim():String.valueOf(tblSinhVien.getValueAt(tblSinhVien.convertRowIndexToModel(row),0));
        if(id.isEmpty()){warn("Chọn sinh viên cần xóa.");
        return;}
        if(JOptionPane.showConfirmDialog(this,"Xóa sinh viên "+id+"? Các điểm danh/điểm liên quan sẽ bị xóa theo CSDL.","Xác nhận"
                ,JOptionPane.YES_NO_OPTION)!=JOptionPane.YES_OPTION)return;
        execute("DELETE FROM sinh_vien WHERE ma_sv=?",id);
        loadSV();clearSV();
    }
    
