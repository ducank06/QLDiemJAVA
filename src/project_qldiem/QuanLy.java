    private void loadSV() {
        DefaultTableModel m=(DefaultTableModel)tblSinhVien.getModel(); 
        m.setRowCount(0);
        String sql="SELECT ma_sv,ho_ten,gioi_tinh,ngay_sinh,email,sdt,dia_chi,ma_lop,trang_thai FROM sinh_vien ORDER BY ma_sv";
        try(Connection c=KNCSDL.getConnection();
            PreparedStatement p=c.prepareStatement(sql);
            ResultSet r=p.executeQuery()){
            while(r.next())m.addRow(new Object[]{r.getString(1),r.getString(2),r.getString(3),r.getDate(4),
                r.getString(5),r.getString(6),r.getString(7),r.getString(8),r.getString(9)});
        }catch(Exception e){showError(e);}
    }
