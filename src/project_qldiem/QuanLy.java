    private void SqlMon(boolean update){
        try{String id=required(txtMaMon,"Mã môn"),name=required(txtTenMon,"Tên môn");
        int sessions=Integer.parseInt(required(txtTongsobuoi,"Tổng số buổi")),
                cc=Integer.parseInt(required(txtTrongsoCC,"Trọng số chuyên cần")),
                mid=Integer.parseInt(required(txtTrongsoGK,"Trọng số giữa kỳ")),
                fin=Integer.parseInt(required(txtTrongsoCK,"Trọng số cuối kỳ"));
        if(sessions<1||cc<0||mid<0||fin<0||cc+mid+fin!=100)
            throw new IllegalArgumentException("Số buổi phải lớn hơn 0; tổng các trọng số phải bằng 100.");
        
        String sql=update?"UPDATE mon_hoc SET ten_mon=?,tong_so_buoi=?,"
                + "trong_so_cc=?,trong_so_gk=?,trong_so_ck=? "
                + "WHERE ma_mon=?":"INSERT INTO mon_hoc(ma_mon,ten_mon,so_tin_chi,tong_so_buoi,trong_so_cc,trong_so_gk,trong_so_ck)"
                + " VALUES(?,?,3,?,?,?,?)";
        try(Connection c=KNCSDL.getConnection();
                PreparedStatement p=c.prepareStatement(sql)){
            if(update){p.setString(1,name);
                p.setInt(2,sessions);p.setInt(3,cc);
                p.setInt(4,mid);p.setInt(5,fin);p.setString(6,id);}
                else{p.setString(1,id);p.setString(2,name);p.setInt(3,sessions);
                p.setInt(4,cc);p.setInt(5,mid);p.setInt(6,fin);}p.executeUpdate();
        }
                loadMon();
                clearMon();
        }catch(Exception e){showError(e);}}
    
