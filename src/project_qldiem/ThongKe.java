    private void timKiemTK() {
    String tuKhoa = txtTimKiem.getText().trim();
    int luaChon = cboTimKiem.getSelectedIndex();

    String[] dieuKien = {
        "sv.ma_sv LIKE ?",
        "sv.ho_ten LIKE ?",
        "l.ma_lop LIKE ?",
        "CAST(COALESCE(g.tong_tin_chi, 0) AS CHAR) LIKE ?",
        "CAST(g.gpa AS CHAR) LIKE ?",
        "xep_loai LIKE ?"
    };

    DefaultTableModel model = (DefaultTableModel) tbTK.getModel();
    model.setRowCount(0);

    String sql =
        "SELECT sv.ma_sv, sv.ho_ten, l.ma_lop, " +
        "       COALESCE(g.tong_tin_chi, 0) AS tin_chi, g.gpa, " +
        "       CASE " +
        "           WHEN g.gpa IS NULL THEN 'Chưa có điểm' " +
        "           WHEN g.gpa >= 3.6 THEN 'Xuất sắc' " +
        "           WHEN g.gpa >= 3.2 THEN 'Giỏi' " +
        "           WHEN g.gpa >= 2.5 THEN 'Khá' " +
        "           WHEN g.gpa >= 2.0 THEN 'Trung bình' " +
        "           WHEN g.gpa >= 1.0 THEN 'Yếu' " +
        "           ELSE 'Kém' " +
        "       END AS xep_loai " +
        "FROM sinh_vien sv " +
        "LEFT JOIN lop l ON l.ma_lop = sv.ma_lop " +
        "LEFT JOIN v_gpa_tich_luy g ON g.ma_sv = sv.ma_sv " +
        (tuKhoa.isEmpty() ? "" : "HAVING " + dieuKien[Math.max(0,Math.min(luaChon, dieuKien.length - 1))]
            + " ") +"ORDER BY sv.ma_sv";

    try (Connection c = KNCSDL.getConnection();
         PreparedStatement p = c.prepareStatement(sql)) {

        if (!tuKhoa.isEmpty()) {
            p.setString(1, "%" + tuKhoa + "%");
        }

        try (ResultSet rs = p.executeQuery()) {
            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("ma_sv"),
                    rs.getString("ho_ten"),
                    rs.getString("ma_lop"),
                    rs.getInt("tin_chi"),
                    rs.getObject("gpa"),
                    rs.getString("xep_loai")
                });
            }
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
        this,
        e.getMessage(),
        "Lỗi truy vấn",
        JOptionPane.ERROR_MESSAGE
    );
    }
}

