    private void loadTK() {
        DefaultTableModel m = (DefaultTableModel) tbTK.getModel();
        m.setRowCount(0);
        m.setColumnIdentifiers(new Object[]{"Mã SV", "Họ tên", "Lớp", "Tín chỉ đạt", "GPA hệ 4", "Xếp loại"});
        String sql = "SELECT sv.ma_sv,sv.ho_ten,l.ma_lop,COALESCE(g.tong_tin_chi,0),g.gpa "
                + "FROM sinh_vien sv JOIN lop l ON l.ma_lop=sv.ma_lop "
                + "LEFT JOIN v_gpa_tich_luy g ON g.ma_sv=sv.ma_sv ORDER BY sv.ma_sv";
        try (Connection c=KNCSDL.getConnection(); PreparedStatement p=c.prepareStatement(sql); ResultSet r=p.executeQuery()) {
            while(r.next()) {
                double gpa=r.getDouble(5);
                String loai=r.wasNull()?"Chưa có điểm":gpa>=3.6?"Xuất sắc":gpa>=3.2?"Giỏi":gpa>=2.5?"Khá":gpa>=2.0?"Trung bình":"Yếu";
                m.addRow(new Object[]{r.getString(1),r.getString(2),
                    r.getString(3),r.getInt(4),
                    r.getObject(5)==null?"-":String.format(java.util.Locale.US,"%.2f",gpa),loai});
            }
        } catch(Exception ex) { JOptionPane.showMessageDialog(this,ex.getMessage(),"Không tải được thống kê",JOptionPane.ERROR_MESSAGE); }
    }
