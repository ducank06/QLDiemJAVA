    private void doiMatKhau() {
        javax.swing.JPasswordField oldPass = new javax.swing.JPasswordField();
        javax.swing.JPasswordField newPass = new javax.swing.JPasswordField();
        Object[] fields = {"Mật khẩu hiện tại", oldPass, "Mật khẩu mới (ít nhất 6 ký tự)", newPass};
        if (javax.swing.JOptionPane.showConfirmDialog(this, fields, "Đổi mật khẩu", 
                javax.swing.JOptionPane.OK_CANCEL_OPTION) != javax.swing.JOptionPane.OK_OPTION) 
            return;
        String sql = "UPDATE tai_khoan SET mat_khau=SHA2(?,256) WHERE ten_dn=? AND mat_khau=SHA2(?,256)";
        try (java.sql.Connection c = KNCSDL.getConnection(); 
                java.sql.PreparedStatement p = c.prepareStatement(sql)) {
            String n = new String(newPass.getPassword());
            if (n.length() < 6) throw new IllegalArgumentException("Mật khẩu mới cần ít nhất 6 ký tự.");
            p.setString(1, n);
            p.setString(2, tenDangNhap);
            p.setString(3, new String(oldPass.getPassword()));
            if (p.executeUpdate() == 0) 
                throw new IllegalArgumentException("Mật khẩu hiện tại không đúng.");
            javax.swing.JOptionPane.showMessageDialog(this, "Đổi mật khẩu thành công.");
        } catch (Exception ex) { javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(), 
                "Không đổi được mật khẩu", javax.swing.JOptionPane.ERROR_MESSAGE); }
    }

